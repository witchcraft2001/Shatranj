; Shipping cold painter with paging/blitter dependencies recorded. Actual
; packed asset pixels and physical mapping are checked in MAME separately.
        DEVICE NOSLOT64K
        ORG 0
        jp start
        DS #100-$,0
        INCLUDE "harness.inc"
        INCLUDE "coldrender_test_defs.inc"
        INCLUDE "fixed_layout.inc"
        INCLUDE "render_aux_test_defs.inc"
start:
        ld sp,#7000
        call t_begin
        ld a,#C3
        ld (ra_render_aux_call),a
        ld hl,lookup
        ld (ra_render_aux_call+1),hl
        ld a,#C3
        ld (ra_gfx_draw_tile_offset),a
        ld hl,record
        ld (ra_gfx_draw_tile_offset+1),hl
        ld a,'K'
        ld (LOWRAM_CHESS_BOARD_ADDR),a
        xor a
        ld (_spectrum_gui_board_flipped),a
        ld (ra_board_background_done),a
        ld (hilite_bg),a
        ld (calls),a
        ld hl,0
        call render_square
        ld a,(calls)
        cp 1
        ld a,1
        call t_expect_z
        ld a,(tile_width)
        cp 24
        ld a,2
        call t_expect_z
        ld a,(tile_rows)
        cp 24
        ld a,3
        call t_expect_z
        ld a,(tile_x_byte)
        cp 8
        ld a,4
        call t_expect_z
        ld a,(tile_y)
        cp 40
        ld a,5
        call t_expect_z
        ld a,(ra_cell_piece)
        or a
        ld a,6
        call t_expect_z
        ld a,(ra_cell_background)
        or a
        ld a,7
        call t_expect_z
        ld a,1
        ld (_spectrum_gui_board_flipped),a
        ld a,8
        ld (hilite_bg),a
        ld hl,0
        call render_square
        ld a,(tile_x_byte)
        cp 176
        ld a,8
        call t_expect_z
        ld a,(tile_y)
        cp 208
        ld a,9
        call t_expect_z
        ld a,(ra_cell_background)
        cp 2
        ld a,10
        call t_expect_z
        ld a,'.'
        ld (LOWRAM_CHESS_BOARD_ADDR),a
        ld hl,0
        call render_square
        ld a,(ra_cell_piece)
        cp #FF
        ld a,11
        call t_expect_z
        call t_end
        halt
lookup:
        ld a,41
        ld (tile_src_page),a
        ld hl,4321
        ld (ra_tile_src_offset),hl
        ret
record:
        ld hl,calls
        inc (hl)
        ret
calls: DB 0
        DS #C000-$,0
        INCBIN "cold_win3_page.bin"
