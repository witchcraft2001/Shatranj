; Execute the shipped coalescer and resident call boundary. Paging and
; accelerator pixel copies require MAME; ticks validates policy and ABI.
        DEVICE NOSLOT64K
        ORG 0
        jp start
        INCLUDE "harness.inc"
        INCLUDE "render_aux_test_defs.inc"

start:
        ld sp,#7000
        call t_begin
        call ra_flip_ring_reset
        ld hl,10
        ld (ra_flip_arg_x),hl
        ld hl,24
        ld (ra_flip_arg_w),hl
        ld a,20
        ld (ra_flip_arg_y),a
        ld a,24
        ld (ra_flip_arg_h),a
        call ra_flip_log_rect
        call ra_flip_log_rect              ; duplicate is eliminated
        ld a,(ra_flip_ring_count)
        cp 1
        ld a,1
        call t_expect_z
        ld hl,34                       ; exact horizontal adjacency
        ld (ra_flip_arg_x),hl
        call ra_flip_log_rect
        ld a,(ra_flip_ring_count)
        cp 1
        ld a,2
        call t_expect_z
        ld hl,(ra_flip_ring+3)
        ld de,48
        or a
        sbc hl,de
        ld a,3
        call t_expect_z
        ld hl,12                       ; fully contained rectangle
        ld (ra_flip_arg_x),hl
        ld hl,2
        ld (ra_flip_arg_w),hl
        ld a,22
        ld (ra_flip_arg_y),a
        ld a,2
        ld (ra_flip_arg_h),a
        call ra_flip_log_rect
        ld a,(ra_flip_ring_count)
        cp 1
        ld a,4
        call t_expect_z
        ; Unequal overlapping rectangles: bounding area 100 <= 60+60.
        call ra_flip_ring_reset
        ld hl,0
        ld (ra_flip_arg_x),hl
        ld hl,10
        ld (ra_flip_arg_w),hl
        xor a
        ld (ra_flip_arg_y),a
        ld a,6
        ld (ra_flip_arg_h),a
        call ra_flip_log_rect
        ld hl,6
        ld (ra_flip_arg_w),hl
        ld a,10
        ld (ra_flip_arg_h),a
        call ra_flip_log_rect
        ld a,(ra_flip_ring_count)
        cp 1
        ld a,5
        call t_expect_z
        ; Sparse disjoint cells overflow to a bounded rectangle, not screen.
        call ra_flip_ring_reset
        ld hl,1
        ld (ra_flip_arg_w),hl
        ld a,1
        ld (ra_flip_arg_h),a
        ld b,9
        ld hl,0
.overflow:
        push hl
        push bc
        ld (ra_flip_arg_x),hl
        call ra_flip_log_rect
        pop bc
        pop hl
        inc hl
        inc hl
        djnz .overflow
        ld a,(ra_flip_ring_count)
        cp 1
        ld a,6
        call t_expect_z
        ld hl,(ra_flip_ring+3)
        ld de,17
        or a
        sbc hl,de
        ld a,7
        call t_expect_z
        ld a,(ra_flip_dirty_all)
        or a
        ld a,8
        call t_expect_z
        ; Height zero means 256, including area arithmetic above 65535.
        call ra_flip_ring_reset
        ld hl,0
        ld (ra_flip_arg_x),hl
        ld hl,320
        ld (ra_flip_arg_w),hl
        xor a
        ld (ra_flip_arg_y),a
        ld (ra_flip_arg_h),a
        call ra_flip_log_rect
        call ra_flip_log_rect
        ld a,(ra_flip_ring_count)
        cp 1
        ld a,9
        call t_expect_z
        ld hl,(ra_flip_ring+3)
        ld de,320
        or a
        sbc hl,de
        ld a,10
        call t_expect_z
        ld a,(ra_flip_ring+5)
        or a
        ld a,11
        call t_expect_z
        call t_end
        halt
        DS #4000-$,0
        INCBIN "build/sprinter/resident.bin"
        DS #C000-$,0
        INCBIN "build/sprinter/render_aux.bin"
